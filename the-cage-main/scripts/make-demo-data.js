#!/usr/bin/env node
/**
 * Freeze the current inventory into public/demo-data.js, for the single-file
 * build to seed itself from.
 *
 *   npm run demo:data
 *
 * The standalone HTML gets passed around — Teams, email, someone's laptop —
 * so it carries only what a demo needs to look real: what the gear is called,
 * what kind it is, and its code. It deliberately does NOT carry:
 *
 *   - who has anything out, or any name or email (the Cheqroom export has
 *     contact and custody columns; none of it belongs in a file that travels)
 *   - serial numbers (an asset register of a six-figure fleet, and useless
 *     for demonstrating anything)
 *   - purchase prices, suppliers, owners
 *
 * The activity in the demo — who has what, what's overdue — is invented by
 * standalone-store.js against made-up crew. Only the gear list is real.
 *
 * Re-run after re-importing inventory, then rebuild:
 *   npm run demo:data && npm run build:standalone
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { q, pool } from '../src/db.js';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

async function main() {
  const { rows } = await q(`
    SELECT code, name, category, brand, model, notes
    FROM items
    WHERE retired = FALSE
    ORDER BY category, name
  `);

  if (!rows.length) {
    console.error('No items in the database. Import an inventory first.');
    process.exit(1);
  }

  /* Belt and braces: the notes column carries the category path and a store
     location, but it is free text and this file gets shared. Drop anything
     that looks like an address before it can travel. */
  const EMAIL = /[^\s@]+@[^\s@]+\.[^\s@]+/g;
  const clean = s => String(s || '').replace(EMAIL, '').trim();

  const items = rows.map(r => ({
    code: r.code,
    name: r.name,
    category: r.category,
    brand: r.brand || '',
    model: r.model || '',
    notes: clean(r.notes)
  }));

  const leaked = items.filter(i => EMAIL.test(JSON.stringify(i)));
  if (leaked.length) {
    console.error(`Refusing to write: ${leaked.length} item(s) still contain an email address.`);
    process.exit(1);
  }

  const cats = [...new Set(items.map(i => i.category))].sort();

  const out = `/**
 * Generated by scripts/make-demo-data.js — do not edit by hand.
 *
 * The real gear list, for the single-file demo to seed from. Names, codes,
 * categories, brands and models only: no people, no serial numbers, no
 * prices. The checkouts and holds in the demo are invented.
 *
 * ${items.length} items across ${cats.length} categories.
 */
export const DEMO_ITEMS = ${JSON.stringify(items, null, 0)};
`;

  writeFileSync(path.join(ROOT, 'public', 'demo-data.js'), out);

  const kb = (Buffer.byteLength(out) / 1024).toFixed(0);
  console.log(`Wrote public/demo-data.js — ${items.length} items, ${cats.length} categories, ${kb} KB.`);
  console.log(`Categories: ${cats.join(', ')}`);
  console.log('No names, emails, serials or prices included.');
  await pool.end();
}

main().catch(async err => {
  console.error('Failed:', err.message);
  await pool.end().catch(() => {});
  process.exit(1);
});
